    parser=argparse.ArgumentParser();parser.add_argument('--tier',choices=['A','B'],default='A')
    parser.add_argument('--version',default='initial');parser.add_argument('--ranks',nargs='*',type=int)
    parser.add_argument('--stop-after-days',type=int)
    args=parser.parse_args();run(args.tier,args.version,args.ranks,args.stop_after_days)
